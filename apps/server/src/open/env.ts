// Open execution (R42; design.md, "Open execution"): eligibility from the repository tree, the environment proposal
// an LLM submits, and the Dockerfile and setup script code renders from it. The simplest version that works:
// every environment is the host's development image plus the repository's own dependencies; the app is not started
// and the Verifier decides by tests only.
import { z } from "zod";

export type OpenLanguage = "python" | "node";
export interface OpenFacts {
  language: OpenLanguage | null;
  /** The repository's own container configuration files, if any. */
  containerConfig: string[];
  /** Dependency files the proposal is written from. */
  dependencyFiles: string[];
  /** Why open execution is not possible here; null when it may be. */
  notPossible: string | null;
}

const CONTAINER = [/^Dockerfile$/, /^dockerfile$/, /^(docker-)?compose\.ya?ml$/, /^\.devcontainer\/devcontainer\.json$/, /^\.devcontainer\/Dockerfile$/];
const PYTHON = [/^pyproject\.toml$/, /^setup\.py$/, /^setup\.cfg$/, /^requirements[^/]*\.txt$/, /^requirements\/[^/]+\.txt$/, /^Pipfile$/, /^tox\.ini$/];
const NODE = [/^package\.json$/, /^package-lock\.json$/];

/** Eligibility from the repository's file paths (R42.2): Python or Node; container configuration noted. */
export function detectOpen(paths: readonly string[]): OpenFacts {
  const set = paths.filter((p) => !p.includes("node_modules/"));
  const containerConfig = set.filter((p) => CONTAINER.some((r) => r.test(p)));
  const py = set.filter((p) => PYTHON.some((r) => r.test(p)));
  const node = set.filter((p) => NODE.some((r) => r.test(p)));
  // A Python project with a small frontend package.json is Python; Node only when there is no Python manifest.
  const language: OpenLanguage | null = py.length > 0 ? "python" : node.length > 0 ? "node" : null;
  return {
    language,
    containerConfig,
    dependencyFiles: language === "python" ? py : language === "node" ? node : [],
    notPossible: language ? null : "open execution supports Python and Node repositories only, and no Python or Node project files were found",
  };
}

const line = z.string().trim().min(1).max(400).refine((s) => !/[\r\n]/.test(s), "one line per command");
export const EnvironmentProposalSchema = z
  .object({
    kind: z.enum(["library", "service"]),
    language: z.enum(["python", "node"]),
    /** Shell commands run once at image build in /opt/target-src, with internet (package indexes from the environment). */
    install: z.array(line).min(1).max(10),
    /** The test command, run in /work without internet; argv form. */
    test: z.array(z.string().min(1).max(200)).min(1).max(12),
    difficulty: z.enum(["simple", "medium", "hard"]),
    risks: z.array(z.string().trim().min(1).max(300)).max(6),
    summary: z.string().trim().min(1).max(600),
  })
  .strict();
export type EnvironmentProposal = z.infer<typeof EnvironmentProposalSchema>;

/** Problems that stop open execution after the proposal (R42.2): a service needs its own container configuration. */
export function proposalProblem(p: EnvironmentProposal, facts: OpenFacts): string | null {
  if (facts.language && p.language !== facts.language) return `the proposal says ${p.language}, but the repository is ${facts.language}`;
  if (p.kind === "service" && facts.containerConfig.length === 0) return "this repository is a service without its own container configuration (Dockerfile, Compose file or devcontainer), so it is not built here";
  return null;
}

/** The setup script run at image build (R42.4): Python into a fresh venv, Node packages prebuilt in the source. */
export function renderSetup(p: EnvironmentProposal): string {
  const head = ["#!/bin/sh", "# Generated by the Studio from the confirmed environment proposal (R42). Runs once at image build.", "set -eu", "cd /opt/target-src"];
  const py = p.language === "python" ? ['python3 -m venv /opt/open-venv', '. /opt/open-venv/bin/activate', 'export PIP_INDEX_URL="${PYPI_INDEX:-https://pypi.org/simple}"', "python -m pip install --upgrade pip"] : ['export npm_config_registry="${NPM_REGISTRY:-https://registry.npmjs.org}"'];
  return [...head, ...py, ...p.install, ""].join("\n");
}

/** The Dockerfile from the fixed template (R42.4): FROM the host's development image; the commands come from setup.sh. */
export function renderDockerfile(baseImage: string, p: EnvironmentProposal): string {
  return [
    "# Generated by the Studio for open execution (R42) from a fixed template; the commands are in setup.sh.",
    `FROM ${baseImage}`,
    "USER root",
    "ARG PYPI_INDEX=https://pypi.org/simple",
    "ARG NPM_REGISTRY=https://registry.npmjs.org",
    "RUN rm -rf /opt/target-src",
    "COPY target-src/ /opt/target-src/",
    "COPY setup.sh /opt/open/setup.sh",
    'RUN PYPI_INDEX="$PYPI_INDEX" NPM_REGISTRY="$NPM_REGISTRY" sh /opt/open/setup.sh',
    ...(p.language === "python" ? ["ENV PATH=/opt/open-venv/bin:$PATH", "ENV PYTHONPATH=/work/src:/work"] : []),
    "WORKDIR /work",
    "",
  ].join("\n");
}

/** What the generated Adapter puts into the development containers (Python: the venv and the changed code first). */
export function openDevEnv(p: EnvironmentProposal): { env: Record<string, string>; prebuilt: string[] } {
  return p.language === "python" ? { env: { PYTHONPATH: "/work/src:/work", VIRTUAL_ENV: "/opt/open-venv" }, prebuilt: [] } : { env: {}, prebuilt: ["node_modules"] };
}

/** The confirm card body (R42.4): what will be built, how hard it looks, and the honest warning. */
export function proposalCardBody(p: EnvironmentProposal, facts: OpenFacts, dockerfile: string, setup: string, previousFailure?: string): string {
  return [
    previousFailure ? `The last build failed: ${previousFailure}\nThis is a changed proposal.\n` : "",
    `Open execution (no Adapter): this will run the repository's own code in containers on this machine. The build may fail; stability is not promised. Development is verified by tests only; the app is not started and there is no demonstration.`,
    `Kind: ${p.kind} · ${p.language} · difficulty: ${p.difficulty}`,
    facts.containerConfig.length ? `The repository's own container configuration: ${facts.containerConfig.join(", ")} (read as a hint)` : "The repository has no container configuration of its own (a library).",
    p.summary,
    p.risks.length ? `Risks:\n${p.risks.map((r) => `- ${r}`).join("\n")}` : "Risks: none named.",
    `Tests: ${p.test.join(" ")}`,
    `Dockerfile:\n${dockerfile}`,
    `setup.sh:\n${setup}`,
  ]
    .filter(Boolean)
    .join("\n\n");
}
